'use strict';
/**
 * Syncs the shared render-survey defaults from the backend into the frontend,
 * and (for the legacy rollback path) recompiles the pre-Vite bundle.
 *
 * `backend/lib/renderPreferences.js` is the single source of truth for the
 * survey-derived 3D render defaults. It must not fork. This script copies it
 * into the frontend in two forms:
 *
 *   frontend/src/lib/renderPreferences.generated.js  - ESM, for the Vite build
 *   frontend/render-preferences.js                   - UMD global, for legacy
 *
 * The ESM form needs no parsing of the UMD wrapper: inside an ES module
 * `typeof module === 'undefined'`, so the factory takes its
 * `root.KeystoneRenderPreferences = factory()` branch and assigns to
 * globalThis. The appended line just re-exports that.
 *
 * The legacy Babel compile of app.jsx -> app.js is kept so the pre-migration
 * site stays shippable. It is skipped automatically if Babel is not installed.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'backend/lib/renderPreferences.js');
const src = fs.readFileSync(source, 'utf8');

// --- 1. ESM form for the Vite build -----------------------------------------
const esmDir = path.join(root, 'frontend/src/lib');
fs.mkdirSync(esmDir, { recursive: true });
fs.writeFileSync(
  path.join(esmDir, 'renderPreferences.generated.js'),
  '// GENERATED by scripts/build-frontend.js from backend/lib/renderPreferences.js.\n' +
    '// Do not edit. Edit the backend file and re-run the script.\n' +
    src +
    '\nexport default globalThis.KeystoneRenderPreferences;\n'
);

// --- 2. UMD form for the legacy bundle --------------------------------------
fs.copyFileSync(source, path.join(root, 'frontend/render-preferences.js'));

console.log('renderPreferences synced (esm + umd)');

// --- 3. Legacy app.js, only if Babel is present -----------------------------
let babel;
try {
  babel = require('../frontend/node_modules/@babel/core');
} catch {
  console.log('legacy app.js: skipped (@babel/core not installed)');
  return;
}

const legacySource = path.join(root, 'frontend/app.jsx');
if (!fs.existsSync(legacySource)) {
  console.log('legacy app.js: skipped (app.jsx removed)');
} else {
  const result = babel.transformFileSync(legacySource, {
    presets: [require.resolve('../frontend/node_modules/@babel/preset-react')],
  });
  fs.writeFileSync(path.join(root, 'frontend/app.js'), result.code + '\n');
  console.log('legacy app.js rebuilt');
}
