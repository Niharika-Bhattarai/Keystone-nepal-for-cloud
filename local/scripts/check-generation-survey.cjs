'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('../frontend/node_modules/playwright');

async function main() {
  const origin = process.env.KEYSTONE_TEST_ORIGIN || 'http://localhost:8093';
  const runId = `${new Date().toISOString().replace(/[:.]/g, '-')}-generation-browser`;
  const out = path.resolve(process.argv[2] || path.join(__dirname, '../tmp/universal-coverage', runId));
  fs.mkdirSync(out,{recursive:true});
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const page = await browser.newPage({viewport:{width:1500,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const preflight = () => page.waitForResponse(r=>r.url().endsWith('/api/plan/preflight') && r.status()===200);
  try {
    await page.goto(origin);
    let checked = preflight();
    await page.getByRole('button',{name:/Open Live Studio|Start a plan/}).first().click();
    assert.equal((await (await checked).json()).supported,true);
    checked = preflight();
    await page.getByText('Bedroom 2',{exact:true}).locator('..').getByRole('button',{name:'Yes',exact:true}).click();
    const bedroomCheck = await checked;
    assert.equal(bedroomCheck.request().postDataJSON().surveyData.privateBaths,'2');
    checked = preflight();
    await page.getByText('Bedroom 2',{exact:true}).locator('..').getByRole('button',{name:'No',exact:true}).click();
    assert.equal((await checked).request().postDataJSON().surveyData.privateBaths,'1');
    await page.getByRole('button',{name:/Structure & Site/}).click();
    checked = preflight();
    await page.getByRole('button',{name:/Square Equal width and depth/}).click();
    assert.equal((await (await checked).json()).supported,false);
    await page.getByText('This footprint shape does not yet have a supported layout family.').waitFor();
    await page.getByRole('button',{name:/Special Features/}).click();
    assert.equal(await page.getByRole('button',{name:'Generate floor plan',exact:true}).isDisabled(),true);
    const study = page.getByRole('button',{name:'Study / home office',exact:true});
    assert.equal(await study.count(),1);
    assert.equal(await study.getAttribute('aria-pressed'),'false');
    await page.screenshot({path:path.join(out,'unsupported-shape.png'),fullPage:true});
    await page.getByRole('button',{name:/Structure & Site/}).click();
    checked = preflight();
    await page.getByRole('button',{name:/Standard Rect Classic proportions/}).click();
    assert.equal((await (await checked).json()).supported,true);
    await page.getByRole('button',{name:/Special Features/}).click();
    assert.equal(await page.getByRole('button',{name:'Generate floor plan',exact:true}).isEnabled(),true);
    checked = preflight();
    await study.click();
    await checked;
    await page.waitForFunction(() => document.querySelector('button[title*="Study and gym together"]')?.disabled);
    assert.equal(await page.getByRole('button',{name:'Gym',exact:true}).isDisabled(),true);
    assert.equal(await study.isEnabled(),true, 'selected rooms remain removable');
    await page.getByRole('button',{name:/Basic Requirements/}).click();
    checked = preflight();
    await page.getByPlaceholder('e.g. 2400').fill('3200');
    await checked;
    await page.getByRole('button',{name:/Special Features/}).click();
    assert.equal(await page.getByRole('button',{name:'Gym',exact:true}).isEnabled(),true);
    checked = preflight();
    await page.getByRole('button',{name:'Gym',exact:true}).click();
    await checked;
    assert.equal(await page.getByRole('button',{name:'Library',exact:true}).isDisabled(),true);
    // Simulate the production fallback policy while retaining an unsupported
    // saved pair after reducing the area. The feature limit must still hold.
    await page.route('**/api/plan/preflight', async route => {
      const response = await route.fetch();
      const data = await response.json();
      await route.fulfill({ response, json: { ...data, legacyFallbackEnabled:true } });
    });
    await page.getByRole('button',{name:/Basic Requirements/}).click();
    checked = preflight();
    await page.getByPlaceholder('e.g. 2400').fill('2400');
    await checked;
    await page.getByRole('button',{name:/Special Features/}).click();
    assert.equal(await page.getByRole('button',{name:'Generate floor plan',exact:true}).isDisabled(),true);
    checked = preflight();
    await page.getByRole('button',{name:'Gym',exact:true}).click();
    await checked;
    assert.equal(await page.getByRole('button',{name:'Generate floor plan',exact:true}).isEnabled(),true);
    checked = preflight();
    await study.click();
    await checked;
    await page.unroute('**/api/plan/preflight');
    const generation = page.waitForResponse(r=>r.url().endsWith('/api/plan') && r.request().method()==='POST');
    await page.getByRole('button',{name:'Generate floor plan',exact:true}).click();
    const result = await (await generation).json();
    assert.equal(result.success,true);
    assert.equal(result.diversityMetrics.valid,true);
    assert.ok(1+result.alternatives.length>=3);
    await page.getByRole('button',{name:'Normal',exact:true}).click();
    await page.screenshot({path:path.join(out,'generated-plan.png'),fullPage:true});
    const unavailablePage = await browser.newPage();
    unavailablePage.on('pageerror',error=>errors.push(error.message));
    await unavailablePage.route('**/api/plan/preflight', () => {});
    await unavailablePage.goto(origin);
    await unavailablePage.getByRole('button',{name:/Open Live Studio|Start a plan/}).first().click();
    await unavailablePage.getByRole('button',{name:/Special Features/}).click();
    await unavailablePage.getByText('The advance check is unavailable. Your choices will be checked when you generate.').waitFor({timeout:12000});
    assert.equal(await unavailablePage.getByRole('button',{name:'Generate floor plan',exact:true}).isEnabled(),true);
    await unavailablePage.close();
    assert.deepEqual(errors,[]);
    const report={passed:true,options:1+result.alternatives.length,diversityValid:true,featureCombinationLimits:true,legacyEnabledFeatureBlock:true,preflightTimeoutRecovery:true,browserErrors:errors};
    fs.writeFileSync(path.join(out,'report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report));
  } finally { await browser.close(); }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
